const express = require('express');
const router = express.Router();
const adminController = require('../controllers/adminController');
const authMiddleware = require('../middlewares/authMiddleware');
const { upload } = require('../middlewares/multer');
const adminAuthMiddleware = require('../middlewares/adminAuthMiddleware');
const masterController = require('../controllers/masterController');
router.post("/login", adminController.login);
router.post('/forget-password', adminController.forgetPassword);
router.post('/verify-reset-otp', adminController.verifyResetOtp);
router.post('/reset-password', adminController.resetPassword);
router.post('/create-company',authMiddleware,upload.single('logo'),adminController.createCompany);
router.get('/companies', authMiddleware, adminController.getAllCompanies);
router.get('/company/:id', authMiddleware, adminController.getCompanyById);
router.put('/company/:id', authMiddleware, upload.single('logo'), adminController.updateCompany);
router.patch('/company/:id/status', authMiddleware, adminController.updateCompanyStatus);
router.get('/masters', adminAuthMiddleware, masterController.listAdminMasters);
router.post('/masters/:type', adminAuthMiddleware, masterController.createMaster);
router.put('/masters/:type/:id', adminAuthMiddleware, masterController.updateMaster);
router.patch('/masters/:type/:id/status', adminAuthMiddleware, masterController.updateMasterStatus);
router.delete('/masters/:type/:id', adminAuthMiddleware, masterController.deleteMaster);
module.exports = router;
